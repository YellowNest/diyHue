logging = logManager.logger.get_logger(__name__)
bridgeConfig = configManager.bridgeConfig.yaml_config


# ---------------------------------------------------------------------------
# MotionAware transient runtime state
# ---------------------------------------------------------------------------

_motionAwareRuntimeLock = RLock()
_motionAwareRuntime = {}
_motionAwareQuietChanged = {}


def motionAwareRuntimeState(area_id):
    with _motionAwareRuntimeLock:
        entry = _motionAwareRuntime.get(area_id)

        if entry is None:
            return None

        value = bool(entry["motion"])

        return {
            "motion": value,
            "motion_valid": True,
            "motion_report": {
                "changed": entry["changed"],
                "motion": value
            }
        }


def clearMotionAwareRuntime(area_id):
    with _motionAwareRuntimeLock:
        _motionAwareRuntime.pop(area_id, None)
        _motionAwareQuietChanged.pop(area_id, None)


def _resetMotionAwareRadioArea(area_id):
    """Reset process-local RF learning after an area lifecycle transition."""
    try:
        from services.mqtt import resetMotionAwareRadioArea
        return resetMotionAwareRadioArea(area_id)
    except Exception as error:
        # The detector is optional in API-only deployments; a failed reset
        # must never prevent the CLIP resource update from being persisted.
        logging.warning(
            "Unable to reset MotionAware RF state for %s: %s",
            area_id,
            error,
        )
        return False




def _isBridgePro():
    return os.getenv("BRIDGE_PROFILE", "").lower() == "pro"


def motionAwareStoredAreas():
    """Return persisted MotionAware overrides without mutating config."""
    return (
        bridgeConfig["config"]
        .get("motion_aware", {})
        .get("areas", {})
    )


def motionAwareStoredArea(area_id):
    return motionAwareStoredAreas().get(area_id, {})


def isMotionAwareAreaRuntimeEnabled(area_id):
    """Whether an area has at least one locally active motion service.

    Area configuration, convenience motion and security motion are separate
    CLIP states.  A stored area alone must not keep the RF worker alive after
    both services have been disabled.  Missing service dictionaries are
    treated as enabled for backwards compatibility with early area records.
    """
    area = motionAwareStoredArea(area_id)
    if not isinstance(area, dict) or area.get("enabled", True) is False:
        return False
    return any(
        not isinstance(area.get(resource_type), dict)
        or area[resource_type].get("enabled", True) is not False
        for resource_type in (
            "convenience_area_motion",
            "security_area_motion",
        )
    )


def _v2BridgeHomeReference():
    """Return the current public bridge-home reference used by CLIP V2.

    The public bridge-home resource is generated by ``v2BridgeHomeId`` from
    the stable bridge identifier.  This must use that same seed: a
    group-0-derived RID is not present in the V2 resource graph, so Hue cannot
    resolve a whole-home area's group relation.

    Persisted records may contain an old group-0-derived RID.  Callers
    canonicalize those records on every GET/reconnect rather than treating
    that obsolete public identifier as authoritative.
    """
    return {
        "rid": str(uuid.uuid5(
            uuid.NAMESPACE_URL,
            bridgeConfig["config"]["bridgeid"] + "bridge_home"
        )),
        "rtype": "bridge_home"
    }


def _canonicalMotionAwareGroupReference(reference, fallback):
    """Map legacy bridge-home references to the stable CLIP identifier."""
    if isinstance(reference, dict) and reference.get("rtype") == "bridge_home":
        return _v2BridgeHomeReference()
    return reference if isinstance(reference, dict) else fallback


def v2MotionAreaCandidateService(device):
    """Return the reference-only MotionAware service for a light device."""
    return {
        "rid": str(uuid.uuid5(
            uuid.NAMESPACE_URL,
            device.id_v2 + "motion_area_candidate"
        )),
        "rtype": "motion_area_candidate"
    }


def devices_for_group(group):
    result = []
    for ref in getattr(group, "lights", []):
        device = ref() if callable(ref) else ref
        if device is not None and hasattr(device, "getDevice") and hasattr(device, "id_v2"):
            result.append(device)
    result.sort(key=lambda item: item.id_v2)
    return result


def _candidate_devices(candidate_ids=None):
    wanted = set(candidate_ids or ())
    result = []
    for group, devices in v2MotionAwareRooms():
        for device in devices:
            rid = v2MotionAreaCandidateService(device)["rid"]
            if not wanted or rid in wanted:
                result.append((group, device, rid))
    return result


def v2MotionAreaDevices(group, area_id=None):
    """Resolve the persisted participant subset without room filtering.

    Hue 5.73 permits a MotionAware area attached to ``bridge_home`` or a
    zone to contain candidates from several rooms. The stored participant
    list is therefore authoritative. The older implementation filtered that
    list to the room used as the stable area-ID anchor, which made a valid
    cross-room area look like it had only one participant after a reload.
    That disabled the participant editor and made the RF worker observe only
    part of the selected area.

    The group argument remains solely as a backwards-compatible fallback for
    legacy room-backed records that predate persisted participants.
    """
    stored = motionAwareStoredArea(area_id or v2MotionAreaIds(group)[0])
    refs = stored.get("participants")
    ids = [r.get("resource", {}).get("rid") for r in refs
           if isinstance(r, dict) and isinstance(r.get("resource"), dict)] if isinstance(refs, list) else []
    if ids:
        candidates = {
            rid: device
            for _candidate_group, device, rid in _candidate_devices(ids)
        }
        # Preserve Hue's submitted order across reloads rather than letting
        # unrelated room membership rewrite the served resource graph.
        selected = [candidates[rid] for rid in ids if rid in candidates]
        if len(selected) == len(ids):
            return selected
        logging.warning(
            "MotionAware area %s has unavailable persisted candidates",
            area_id,
        )
        return selected
    return devices_for_group(group)


def v2MotionAwareRooms():
    """Return rooms providing candidate devices, irrespective of room size.

    The three/four participant constraint belongs to area POST/PUT validation.
    It must not hide candidates in rooms with fewer or more lights.
    """
    if not _isBridgePro():
        return []

    result = []

    for group in bridgeConfig["groups"].values():
        if getattr(group, "type", None) != "Room":
            continue

        devices = []

        for device_ref in group.lights:
            device = device_ref() if callable(device_ref) else device_ref

            if (
                device is not None
                and hasattr(device, "getDevice")
                and hasattr(device, "id_v2")
            ):
                devices.append(device)

        if devices:
            devices.sort(key=lambda item: item.id_v2)
            result.append((group, devices))

    result.sort(key=lambda item: item[0].getV2Room()["id"])

    # An area limit is not a limit on rooms offered during lamp selection.
    return result


def v2MotionAreaIds(group):
    room_id = group.getV2Room()["id"]

    area_id = str(uuid.uuid5(
        uuid.NAMESPACE_URL,
        room_id + "motion_area_configuration"
    ))

    convenience_id = str(uuid.uuid5(
        uuid.NAMESPACE_URL,
        area_id + "convenience_area_motion"
    ))

    security_id = str(uuid.uuid5(
        uuid.NAMESPACE_URL,
        area_id + "security_area_motion"
    ))

    return area_id, convenience_id, security_id


def v2MotionAreaConfiguration(group, devices):
    area_id, convenience_id, security_id = v2MotionAreaIds(group)
    stored = motionAwareStoredArea(area_id)
    devices = v2MotionAreaDevices(group, area_id)
    group_reference = _canonicalMotionAwareGroupReference(
        stored.get("group"),
        {
            "rid": group.getV2Room()["id"],
            "rtype": "room"
        }
    )

    return {
        "id": area_id,
        "name": stored.get("name", group.name),
        "group": group_reference,
        "participants": [
            {
                "resource": v2MotionAreaCandidateService(device),
                "status": {
                    "health": "healthy"
                }
            }
            for device in devices
        ],
        "services": [
            {
                "rid": convenience_id,
                "rtype": "convenience_area_motion"
            },
            {
                "rid": security_id,
                "rtype": "security_area_motion"
            }
        ],
        "health": stored.get("health", "healthy"),
        "enabled": stored.get("enabled", True),
        "type": "motion_area_configuration"
    }


def v2MotionAwareSources(group):
    """Return regular diyHue motion sources assigned to a room."""
    result = []

    for member_ref in getattr(group, "sensors", []):
        member = member_ref() if callable(member_ref) else member_ref

        if member is None:
            continue

        if hasattr(member, "getMotion"):
            motion = member.getMotion()

            if motion is not None:
                result.append(member)
                continue

        if getattr(member, "type", None) == "ZLLPresence":
            result.append(member)

    result.sort(
        key=lambda item: getattr(
            item,
            "id_v2",
            getattr(item, "id_v1", "")
        )
    )

    return result


def v2MotionAwareState(group):
    """Aggregate ordinary room motion sensors into one area state."""

    area_id, _, _ = v2MotionAreaIds(group)

    runtime_state = motionAwareRuntimeState(
        area_id
    )

    if runtime_state is not None:
        return runtime_state

    reports = []

    for source in v2MotionAwareSources(group):
        if hasattr(source, "getMotion"):
            resource = source.getMotion()

            if resource is None or not resource.get("enabled", True):
                continue

            motion = resource.get("motion", {})

            if "motion" not in motion:
                continue

            changed = (
                motion.get("motion_report") or {}
            ).get("changed")

            reports.append({
                "motion": bool(motion["motion"]),
                "changed": changed
            })

        elif getattr(source, "type", None) == "ZLLPresence":
            if not source.config.get("on", True):
                continue

            if "presence" not in source.state:
                continue

            reports.append({
                "motion": bool(source.state["presence"]),
                "changed": source.state.get("lastupdated")
            })

    if not reports:
        return {
            "motion": False,
            # A room containing only light participants has no native motion
            # source. Treat the observed quiet state as valid so the stock
            # calibration flow can complete while the area is empty.
            "motion_valid": True,
            # The stock app also expects a motion_report record while it
            # waits for calibration/reconnect updates.  A quiet room is a
            # valid observation; publish it with a fresh timestamp rather
            # than leaving the report absent.
            "motion_report": {
                "changed": _quiet_changed(area_id),
                "motion": False
            }
        }

    result = {
        "motion": any(report["motion"] for report in reports),
        "motion_valid": True
    }

    changed = sorted(
        report["changed"]
        for report in reports
        if report["changed"]
        and report["changed"] != "none"
    )

    if changed:
        result["motion_report"] = {
            "changed": changed[-1],
            "motion": result["motion"]
        }

    return result


def _quiet_changed(area_id):
    with _motionAwareRuntimeLock:
        value = _motionAwareQuietChanged.get(area_id)
        if value is None:
            value = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            _motionAwareQuietChanged[area_id] = value
        return value


def v2AreaMotion(group, area_id, resource_id, resource_type):
    stored = (
        motionAwareStoredArea(area_id)
        .get(resource_type, {})
    )

    return {
        "id": resource_id,
        "owner": {
            "rid": area_id,
            "rtype": "motion_area_configuration"
        },
        "enabled": stored.get("enabled", True),
        "motion": v2MotionAwareState(group),
        "sensitivity": {
            "sensitivity": stored.get("sensitivity", 2),
            "sensitivity_max": 4
        },
        "type": resource_type
    }


def v2MotionAwareResources():
    resources = {
        "motion_area_configuration": [],
        "convenience_area_motion": [],
        "security_area_motion": [],
    }

    for group, devices in v2MotionAwareRooms():
        area_id, convenience_id, security_id = v2MotionAreaIds(group)

        # Eligible rooms provide candidates, but an area does not exist
        # until the app has successfully created and persisted it.
        if area_id not in motionAwareStoredAreas():
            continue

        resources["motion_area_configuration"].append(
            v2MotionAreaConfiguration(group, devices)
        )

        resources["convenience_area_motion"].append(
            v2AreaMotion(
                group,
                area_id,
                convenience_id,
                "convenience_area_motion"
            )
        )

        resources["security_area_motion"].append(
            v2AreaMotion(
                group,
                area_id,
                security_id,
                "security_area_motion"
            )
        )

    return resources


def findMotionAwareResource(resource_type, resource_id):
    """Resolve one generated MotionAware resource by V2 id."""
    if resource_type not in (
        "motion_area_configuration",
        "convenience_area_motion",
        "security_area_motion",
    ):
        return None

    for resource in v2MotionAwareResources()[resource_type]:
        if resource["id"] == resource_id:
            return resource

    return None


def _streamMotionAwareResources(event_type, resources):
    """Publish independently decodable MotionAware resource events."""
    for resource in resources:
        StreamEvent({
            "creationtime": datetime.now(timezone.utc).strftime(
                "%Y-%m-%dT%H:%M:%SZ"
            ),
            "data": [resource],
            "id": str(uuid.uuid4()),
            "type": event_type,
        })


def createMotionAwareArea(data):
    """Create an area from the candidate references sent by the Hue app."""
    if not _isBridgePro():
        return None

    if not isinstance(data, dict):
        raise ValueError("POST body must be an object")

    name = data.get("name")
    group_ref = data.get("group")
    participants = data.get("participants")

    if not isinstance(name, str) or not name.strip():
        raise ValueError("name must be a non-empty string")

    if (
        not isinstance(group_ref, dict)
        or not isinstance(group_ref.get("rid"), str)
        or group_ref.get("rtype") not in ("bridge_home", "room", "zone")
    ):
        raise ValueError("group must reference a bridge_home, room, or zone")

    # The app can legitimately submit the ID it cached before a restart.
    # Store the stable public reference rather than diyHue's volatile group-0
    # helper ID so the area remains valid on every later reconnect.
    if group_ref["rtype"] == "bridge_home":
        group_ref = _v2BridgeHomeReference()

    if not isinstance(participants, list) or not 3 <= len(participants) <= 4:
        raise ValueError("participants must contain three or four devices")

    candidate_ids = []

    for participant in participants:
        resource = participant.get("resource", {}) if isinstance(participant, dict) else {}

        if resource.get("rtype") != "motion_area_candidate" or not resource.get("rid"):
            raise ValueError("each participant must reference a motion_area_candidate")

        candidate_ids.append(resource["rid"])

    if len(set(candidate_ids)) != len(candidate_ids):
        raise ValueError("participants must be unique")

    selected_room = None
    for group, devices in v2MotionAwareRooms():
        room_candidates = {v2MotionAreaCandidateService(device)["rid"] for device in devices}
        if set(candidate_ids).issubset(room_candidates):
            selected_room = group
            break
    # A Bridge Pro zone may contain compatible lights from multiple rooms.
    # Candidate resources are bridge-wide, so do not reject a valid zone
    # selection merely because its participants do not share one room.
    if selected_room is None and group_ref.get("rtype") in ("bridge_home", "zone"):
        matches = _candidate_devices(candidate_ids)
        if len(matches) == len(candidate_ids):
            selected_room = matches[0][0]

    if selected_room is None:
        raise ValueError("participants do not form an eligible MotionAware room")

    area_id, _, _ = v2MotionAreaIds(selected_room)
    config = bridgeConfig["config"]
    areas = config.setdefault("motion_aware", {}).setdefault("areas", {})
    area = areas.setdefault(area_id, {})
    area["name"] = name.strip()
    area["group"] = {
        "rid": group_ref["rid"],
        "rtype": group_ref["rtype"]
    }
    area.setdefault("enabled", True)
    area["participants"] = [
        {"resource": {"rid": rid, "rtype": "motion_area_candidate"},
         "status": {"health": "healthy"}}
        for rid in candidate_ids
    ]
    # The stock app waits for a healthy area event before leaving the
    # creation screen.  A diyHue-backed room has no hardware calibration
    # phase, so expose the ready state immediately.
    area["health"] = "healthy"

    configManager.bridgeConfig.save_config(backup=False, resource="config")

    resources = v2MotionAwareResources()
    created = findMotionAwareResource("motion_area_configuration", area_id)

    event_data = [created]

    for resource_type in (
        "convenience_area_motion",
        "security_area_motion",
    ):
        event_data.extend(
            item for item in resources[resource_type]
            if item["owner"]["rid"] == area_id
        )

    _streamMotionAwareResources("add", event_data)

    Thread(
        target=_finishMotionAwareCalibration,
        args=(area_id,),
        daemon=True
    ).start()

    return created


def _finishMotionAwareCalibration(area_id):
    """Publish the post-create health transition awaited by the Hue app."""
    sleep(1.5)
    area = motionAwareStoredArea(area_id)

    if not area:
        return

    # The app installs its reducer after the POST future completes. Repeat
    # the creation event once after that boundary so it cannot be missed.
    current = findMotionAwareResource("motion_area_configuration", area_id)
    if current is None:
        return
    resources = v2MotionAwareResources()
    event_data = [current]
    for resource_type in (
        "convenience_area_motion",
        "security_area_motion",
    ):
        event_data.extend(
            item for item in resources[resource_type]
            if item["owner"]["rid"] == area_id
        )
    _streamMotionAwareResources("add", event_data)

    area["health"] = "healthy"
    configManager.bridgeConfig.save_config(backup=False, resource="config")
    # The stock app decodes update events as complete resources.  Sending
    # only {id,type,health} leaves its cached area without group/participants
    # and is reported as a failed start even though creation succeeded.
    current = findMotionAwareResource("motion_area_configuration", area_id)
    if current is None:
        return
    resources = v2MotionAwareResources()
    event_data = [current]
    for resource_type in (
        "convenience_area_motion",
        "security_area_motion",
    ):
        event_data.extend(
            item for item in resources[resource_type]
            if item["owner"]["rid"] == area_id
        )
    _streamMotionAwareResources("update", event_data)


def deleteMotionAwareArea(area_id):
    """Delete a persisted MotionAware area and all generated services."""
    areas = bridgeConfig["config"].get("motion_aware", {}).get("areas", {})

    if area_id not in areas:
        return False

    current = findMotionAwareResource("motion_area_configuration", area_id)
    service_ids = [service["rid"] for service in current.get("services", [])] if current else []

    # A behavior instance sourced by this area is not useful once the area
    # disappears.  Leaving it in the CLIP graph creates a dangling source
    # reference which Hue presents as an externally removed/failed rule.
    # Do not touch normal automation behavior instances.
    deleted_behaviors = []
    for behavior_id, instance in list(
        bridgeConfig.get("behavior_instance", {}).items()
    ):
        configuration = getattr(instance, "configuration", {})
        if not isinstance(configuration, dict):
            continue
        if configuration.get("source") != {
            "rid": area_id,
            "rtype": "motion_area_configuration"
        }:
            continue
        del bridgeConfig["behavior_instance"][behavior_id]
        deleted_behaviors.append(behavior_id)

    del areas[area_id]
    configManager.bridgeConfig.save_config(backup=False, resource="config")
    if deleted_behaviors:
        configManager.bridgeConfig.save_config(
            backup=False, resource="behavior_instance"
        )

    StreamEvent({
        "creationtime": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "data": [
            {"id": area_id, "type": "motion_area_configuration"},
            *[
                {"id": service_id, "type": resource_type}
                for service_id, resource_type in zip(
                    service_ids,
                    ("convenience_area_motion", "security_area_motion")
                )
            ],
            *[
                {"id": behavior_id, "type": "behavior_instance"}
                for behavior_id in deleted_behaviors
            ]
        ],
        "id": str(uuid.uuid4()),
        "type": "delete"
    })

    return True


def updateMotionAwareResource(resource_type, resource_id, data):
    """Persist a supported MotionAware V2 PUT and emit its SSE update."""
    if not _isBridgePro():
        return None

    current = findMotionAwareResource(
        resource_type,
        resource_id
    )

    if current is None:
        return None

    if not isinstance(data, dict):
        raise ValueError("PUT body must be an object")

    area_id = (
        resource_id
        if resource_type == "motion_area_configuration"
        else current["owner"]["rid"]
    )
    runtime_was_enabled = isMotionAwareAreaRuntimeEnabled(area_id)

    changes = {}

    if resource_type == "motion_area_configuration":
        if "name" in data:
            if (
                not isinstance(data["name"], str)
                or not data["name"].strip()
            ):
                raise ValueError("name must be a non-empty string")

            changes["name"] = data["name"]

        if "enabled" in data:
            if not isinstance(data["enabled"], bool):
                raise ValueError("enabled must be boolean")

            changes["enabled"] = data["enabled"]

        if "participants" in data:
            participants = data["participants"]
            if not isinstance(participants, list) or not 3 <= len(participants) <= 4:
                raise ValueError("participants must contain three or four devices")
            ids = []
            for participant in participants:
                resource = participant.get("resource", {}) if isinstance(participant, dict) else {}
                if resource.get("rtype") != "motion_area_candidate" or not isinstance(resource.get("rid"), str):
                    raise ValueError("invalid participant candidate")
                ids.append(resource["rid"])
            if len(set(ids)) != len(ids) or len(_candidate_devices(ids)) != len(ids):
                raise ValueError("participants must be unique eligible candidates")
            changes["participants"] = [
                {"resource": {"rid": rid, "rtype": "motion_area_candidate"},
                 "status": {"health": "healthy"}}
                for rid in ids
            ]

    else:
        if "enabled" in data:
            if not isinstance(data["enabled"], bool):
                raise ValueError("enabled must be boolean")

            changes["enabled"] = data["enabled"]

        if "sensitivity" in data:
            sensitivity = data["sensitivity"]

            if not isinstance(sensitivity, dict):
                raise ValueError(
                    "sensitivity must be an object"
                )

            if "sensitivity" not in sensitivity:
                raise ValueError(
                    "sensitivity.sensitivity is required"
                )

            value = sensitivity["sensitivity"]

            if (
                isinstance(value, bool)
                or not isinstance(value, int)
                or not 0 <= value <= 4
            ):
                raise ValueError(
                    "sensitivity must be an integer from 0 to 4"
                )

            changes["sensitivity"] = value

    if not changes:
        return current

    # Do not persist or emit an SSE update when the requested
    # properties already match the generated resource state.
    effective_changes = {}

    for key, value in changes.items():
        if key == "sensitivity":
            current_value = (
                current.get("sensitivity", {})
                .get("sensitivity")
            )
        else:
            current_value = current.get(key)

        if current_value != value:
            effective_changes[key] = value

    changes = effective_changes

    if not changes:
        return current

    config = bridgeConfig["config"]
    motion_aware = config.setdefault(
        "motion_aware",
        {}
    )
    areas = motion_aware.setdefault(
        "areas",
        {}
    )
    area = areas.setdefault(
        area_id,
        {}
    )

    if resource_type == "motion_area_configuration":
        area.update(changes)
    else:
        service = area.setdefault(
            resource_type,
            {}
        )
        service.update(changes)

    runtime_is_enabled = isMotionAwareAreaRuntimeEnabled(area_id)

    configManager.bridgeConfig.save_config(
        backup=False,
        resource="config"
    )

    # Enabling/disabling is an RF detector lifecycle boundary.  The learned
    # baseline, prior hold and temporal confirmation must not survive a user
    # toggle or the next enable can emit stale motion (or suppress a valid
    # first motion through old deduplication state).
    if "enabled" in changes and runtime_was_enabled != runtime_is_enabled:
        if not runtime_is_enabled:
            setMotionAwareRuntimeMotion(
                area_id,
                False,
                source="configuration",
            )
        else:
            clearMotionAwareRuntime(area_id)
        _resetMotionAwareRadioArea(area_id)

    updated = findMotionAwareResource(
        resource_type,
        resource_id
    )

    # V2 clients decode update events as complete resources; partial payloads
    # lose participants/services and leave the creation UI spinning.
    event_data = updated

    StreamEvent({
        "creationtime": datetime.now(timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%SZ"
        ),
        "data": [event_data],
        "id": str(uuid.uuid4()),
        "type": "update"
    })

    return updated



def _motionAreaBehaviorEnabled(area_id, configuration):
    area = motionAwareStoredArea(area_id)
    if not area or area.get("enabled", True) is False:
        return False
    service = configuration.get("motion", {}).get("motion_service", {})
    if service.get("rtype") != "convenience_area_motion":
        return False
    expected = str(uuid.uuid5(uuid.NAMESPACE_URL, area_id + "convenience_area_motion"))
    return service.get("rid") == expected and area.get("convenience_area_motion", {}).get("enabled", True) is not False


def _motionAreaBehaviorActions(configuration, value):
    """Select a validated wall-clock timeslot, including midnight wraparound."""
    slots = configuration.get("motion", {}).get("when", {}).get("timeslots", [])
    choices = []
    for slot in slots:
        time_value = slot.get("start_time", {}).get("time", {})
        hour, minute = time_value.get("hour"), time_value.get("minute")
        if type(hour) is not int or type(minute) is not int or not (0 <= hour < 24 and 0 <= minute < 60):
            continue
        choices.append((hour * 60 + minute, slot))
    if not choices:
        return {}
    choices.sort(key=lambda item: item[0])
    now = datetime.now()
    elapsed = now.hour * 60 + now.minute
    applicable = [slot for start, slot in choices if start <= elapsed]
    slot = applicable[-1] if applicable else choices[-1][1]
    return slot.get("on_motion" if value else "on_no_motion", {})


def _runMotionAreaActions(configuration, actions):
    """Use existing scene/group interfaces; participants are not action targets."""
    for entry in actions.get("recall_single", []):
        action = entry.get("action")
        if isinstance(action, dict) and action.get("recall", {}).get("rtype") == "scene":
            rid = action["recall"]["rid"]
            scene = next((s for s in bridgeConfig.get("scenes", {}).values() if s.id_v2 == rid), None)
            if scene is not None:
                scene.activate({"seconds": 1, "minutes": 0})
                logging.info("MotionAware behavior recalled scene=%s", rid)
        elif action == "last_on":
            # Hue uses `last_on` as the default action in a newly-created
            # MotionAware time slot.  It is an action on the configured
            # target group, not on the RF participants themselves.  Reuse the
            # normal group command path so room/zone membership and the light
            # backend remain authoritative.
            for target in configuration.get("motion", {}).get("where", []):
                reference = target.get("group", {})
                rtype = reference.get("rtype")
                if rtype not in ("room", "zone"):
                    continue
                for group in bridgeConfig.get("groups", {}).values():
                    group_id = str(uuid.uuid5(
                        uuid.NAMESPACE_URL,
                        group.id_v2 + rtype,
                    ))
                    if group_id == reference.get("rid"):
                        group.setV1Action({"on": True})
                        logging.info(
                            "MotionAware behavior last_on group=%s type=%s",
                            group.id_v1,
                            rtype,
                        )
        elif action == "all_off":
            for target in configuration.get("motion", {}).get("where", []):
                reference = target.get("group", {})
                rtype = reference.get("rtype")
                if rtype not in ("room", "zone"):
                    continue
                for group in bridgeConfig.get("groups", {}).values():
                    if str(uuid.uuid5(uuid.NAMESPACE_URL, group.id_v2 + rtype)) == reference.get("rid"):
                        group.setV1Action({"on": False})


def _dispatchMotionAreaBehaviors(area_id, value):
    """Execute the local behavior contract observed in Hue-created instances."""
    transition = _motionAwareRuntime.get(area_id)
    # Hue can leave historical instances behind after editing/recreating an
    # area.  Running all of them recalls stale scenes and lights.  Persistence
    # order is insertion order, so the last matching instance is the current
    # app configuration and is the only one that should run.
    matching = []
    for instance in list(bridgeConfig.get("behavior_instance", {}).values()):
        try:
            configuration = instance.configuration
            if not instance.enabled or configuration.get("source") != {"rid": area_id, "rtype": "motion_area_configuration"}:
                continue
            if not _motionAreaBehaviorEnabled(area_id, configuration):
                continue
            matching.append(instance)
        except (AttributeError, KeyError, TypeError, ValueError):
            logging.warning("Skipped malformed MotionAware behavior")

    if not matching:
        return
    instance = matching[-1]
    configuration = instance.configuration
    signature = json.dumps(configuration, sort_keys=True)
    actions = _motionAreaBehaviorActions(configuration, value)
    if not actions:
        return
    if value:
        _runMotionAreaActions(configuration, actions)
        return
    delay = actions.get("after", {})
    minutes, seconds = delay.get("minutes", 0), delay.get("seconds", 0)
    if any(type(n) is not int or n < 0 for n in (minutes, seconds)):
        return

    def finish(instance=instance, configuration=configuration, actions=actions, signature=signature):
        # New motion, area deletion, disabled/edited behavior or service
        # cancels the delayed action without mutating persisted data.
        if _motionAwareRuntime.get(area_id) is not transition:
            return
        if not any(obj is instance for obj in bridgeConfig.get("behavior_instance", {}).values()):
            return
        if not instance.enabled or json.dumps(instance.configuration, sort_keys=True) != signature:
            return
        if _motionAreaBehaviorEnabled(area_id, configuration):
            _runMotionAreaActions(configuration, actions)

    timer = Timer(minutes * 60 + seconds, finish)
    timer.daemon = True
    timer.start()


def setMotionAwareRuntimeMotion(
    area_id,
    value,
    source="radio"
):
    """
    Change live MotionAware state.

    This state is intentionally NOT persisted to config.yaml.
    """
    if not _isBridgePro():
        return []

    if area_id not in motionAwareStoredAreas():
        return []

    value = bool(value)

    with _motionAwareRuntimeLock:
        current = _motionAwareRuntime.get(
            area_id
        )

        if (
            current is not None
            and bool(current["motion"]) == value
        ):
            return []

    before = motionAwareSnapshot()

    changed = (
        datetime.now(timezone.utc)
        .strftime("%Y-%m-%dT%H:%M:%SZ")
    )

    with _motionAwareRuntimeLock:
        _motionAwareRuntime[area_id] = {
            "motion": value,
            "changed": changed,
            "source": str(source),
        }

    updates = streamMotionAwareTransitions(
        before
    )

    _dispatchMotionAreaBehaviors(area_id, value)

    logging.info(
        "MotionAware runtime area=%s "
        "motion=%s source=%s updates=%s",
        area_id,
        value,
        source,
        len(updates),
    )

    return updates


def setMotionAwareDebugMotion(
    resource_type,
    resource_id,
    value
):
    """
    Temporary compatibility hook for the manual test endpoint.

    It now writes runtime state only.
    """
    if resource_type not in (
        "convenience_area_motion",
        "security_area_motion",
    ):
        return None

    current = findMotionAwareResource(
        resource_type,
        resource_id
    )

    if current is None:
        return None

    area_id = current["owner"]["rid"]

    setMotionAwareRuntimeMotion(
        area_id,
        bool(value),
        source="debug-api",
    )

    return findMotionAwareResource(
        resource_type,
        resource_id
    )


def motionAwareSnapshot():
    """Capture transition-relevant MotionAware state."""
    if not _isBridgePro():
        return {}

    try:
        resources = v2MotionAwareResources()
    except Exception as err:
        logging.warning(
            "Unable to snapshot MotionAware state: %s",
            err
        )
        return {}

    snapshot = {}

    for resource_type in (
        "convenience_area_motion",
        "security_area_motion",
    ):
        for resource in resources[resource_type]:
            motion = resource.get("motion", {})

            snapshot[(resource_type, resource["id"])] = (
                bool(motion.get("motion", False)),
                bool(motion.get("motion_valid", False)),
            )

    return snapshot


def streamMotionAwareTransitions(before):
    """Emit V2 updates only when aggregate area motion changes."""
    if not before:
        return []

    if not _isBridgePro():
        return []

    try:
        resources = v2MotionAwareResources()
    except Exception as err:
        logging.warning(
            "Unable to build MotionAware transition: %s",
            err
        )
        return []

    updates = []

    for resource_type in (
        "convenience_area_motion",
        "security_area_motion",
    ):
        for resource in resources[resource_type]:
            key = (resource_type, resource["id"])

            if key not in before:
                continue

            motion = resource.get("motion", {})

            after = (
                bool(motion.get("motion", False)),
                bool(motion.get("motion_valid", False)),
            )

            if before[key] == after:
                continue

            # Hue app decodes MotionAware UPDATE data as complete
            # resources.  A motion-only patch can be ignored or leave
            # the client's cached resource incomplete.
            updates.append(resource)

    if not updates:
        return []

    # Use the same independently-decodable full-resource event path
    # already required by the Hue app during MotionAware calibration.
    _streamMotionAwareResources(
        "update",
        updates
    )

    return updates
